export function formatMXN(value: number) {
  return `$${Math.round(value).toLocaleString('es-MX')} MXN`;
}

export function landedCost(plant: Plant) {
  return grossCostBeforeDelivery(plant) + plant.deliveryReserve;
}

export function grossProfit(plant: Plant) {
  return plant.retailPrice - grossCostBeforeDelivery(plant);
}

export function grossMargin(plant: Plant) {
  return Math.round((grossProfit(plant) / plant.retailPrice) * 100);
}

export function grossCostBeforeDelivery(plant: Plant) {
  return plant.acquisitionCost + plant.packagingCost;
}

export function netProfitAfterDelivery(plant: Plant) {
  return plant.retailPrice - landedCost(plant);
}

export function netMarginAfterDelivery(plant: Plant) {
  return Math.round((netProfitAfterDelivery(plant) / plant.retailPrice) * 100);
}

export function markupOverCost(plant: Plant) {
  return Math.round((netProfitAfterDelivery(plant) / landedCost(plant)) * 100);
}
